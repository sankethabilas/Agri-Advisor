# Rule BR-1 / BR-2: Standard Team-Agreed Advisory Disclaimer
ADVISORY_DISCLAIMER = (
    "This advisory is generated by an AI system to support your decision-making. "
    "It does not replace professional agricultural extension advice. "
    "For severe or uncertain cases, please consult your local Agriculture Extension Officer."
)

AGRICULTURE_HELPLINE = "1920 (Department of Agriculture Toll-Free)"


