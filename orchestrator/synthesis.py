# T-18.2 & T-18.6: Prompt Builder with Token Cost Optimization
# ==============================================================================

class PromptBuilder:
    """
    Constructs grounded, token-optimized prompts for LLM response synthesis.
    """

    SYSTEM_PROMPT = (
        "You are Agri-Advisor, an expert agricultural extension AI assistant developed for Sri Lankan farmers "
        "in collaboration with the Department of Agriculture (DOA).\n\n"
        "### CORE INSTRUCTIONS & GROUNDING RULES (Rule BR-9):\n"
        "1. STRICT GROUNDING: Use ONLY the verified specialist agent outputs and RAG context provided below. "
        "Do NOT invent unverified chemical names, dosage rates, or facts not present in the context.\n"
        "2. UNCERTAINTY: If information about a specific treatment or practice is missing from the context, state "
        "'I do not have sufficient verified information for this aspect; please consult your local extension officer.'\n"
        "3. FORMATTING: Structure your advisory strictly according to the Eight-Block Layout defined below.\n"
        "4. TONE: Clear, practical, farmer-friendly language. Avoid overly dense academic jargon.\n"
        "5. WEATHER-AWARE (Rule BR-12): If rain or high moisture is forecast, explicitly advise postponing chemical sprays."
    )

    @staticmethod
    def _format_compact_disease(disease_res: Optional[DiseaseDiagnoseResponse]) -> Optional[Dict[str, Any]]:
        if not disease_res:
            return None
        return {
            "disease": disease_res.disease,
            "confidence": f"{int(disease_res.confidence * 100)}%",
            "severity": disease_res.severity,
            "chemical_treatments": [
                f"{c.name} ({c.dosage}) - PHI: {c.pre_harvest_interval_days} days. {c.instructions}"
                for c in disease_res.treatment.chemical
            ],
            "organic_treatments": [
                f"{o.name} ({o.dosage}) - {o.instructions}"
                for o in disease_res.treatment.organic
            ],
            "cultural_treatments": [
                f"{cu.practice}: {cu.description}"
                for cu in disease_res.treatment.cultural
            ],
            "prevention": disease_res.prevention,
            "source": disease_res.source,
        }

    @staticmethod
    def _format_compact_weather(weather_res: Optional[WeatherAdviceResponse]) -> Optional[Dict[str, Any]]:
        if not weather_res:
            return None
        return {
            "condition": weather_res.current.condition,
            "temperature_c": weather_res.current.temperature_c,
            "humidity_pct": weather_res.current.humidity_pct,
            "rainfall_mm": weather_res.current.rainfall_mm,
            "disease_risk_level": weather_res.disease_risk.level,
            "disease_risk_factors": weather_res.disease_risk.contributing_factors,
            "advisory": weather_res.advisory,
            "alerts": [
                f"[{a.severity.upper()}] {a.title}: {a.recommended_action}"
                for a in weather_res.alerts
            ],
        }

    @staticmethod
    def _format_compact_crop(crop_res: Optional[CropAdviceResponse]) -> Optional[Dict[str, Any]]:
        if not crop_res:
            return None
        return {
            "crop": crop_res.crop,
            "season": crop_res.season,
            "zone": crop_res.agro_ecological_zone,
            "sections": crop_res.advisory_sections,
            "source": crop_res.source,
        }

    @classmethod
    def build_user_prompt(
        cls,
        request: OrchestratorProcessRequest,
        routing_res: RoutingResult,
    ) -> str:
        """
        Builds the synthesis prompt containing all agent data and RAG context (T-18.2, T-18.6).
        """
        compact_disease = cls._format_compact_disease(routing_res.disease_response)
        compact_weather = cls._format_compact_weather(routing_res.weather_response)
        compact_crop = cls._format_compact_crop(routing_res.crop_response)

        rag_context = ""
        if routing_res.rag_response and routing_res.rag_response.context:
            rag_context = routing_res.rag_response.context.strip()
        elif routing_res.rag_response and routing_res.rag_response.sources:
            rag_context = "\n\n".join(
                f"[{s.title} ({s.source})]: {s.content}"
                for s in routing_res.rag_response.sources
            )

        prompt_data = {
            "farmer_query": request.query,
            "language": request.language,
            "crop": routing_res.crop,
            "district": request.location.district,
            "agro_ecological_zone": request.location.agro_ecological_zone or "Dry Zone",
            "intent": routing_res.intent,
            "disease_findings": compact_disease,
            "weather_and_risks": compact_weather,
            "crop_cultivation_data": compact_crop,
            "verified_rag_corpus_context": rag_context or "No specific corpus passages retrieved.",
        }

        user_prompt = f"""FARMER QUERY & AGENT RESULTS:
```json
{json.dumps(prompt_data, indent=2, ensure_ascii=False)}
```

Synthesize a comprehensive, beautifully formatted Markdown advisory following the EXACT EIGHT-BLOCK LAYOUT below:

### REQUIRED EIGHT-BLOCK ADVISORY LAYOUT (Subtask T-18.3):
1. **Header**: `# 🌾 Advisory for <Crop> (<District>)` followed by a concise plain-language restatement.
2. **Diagnosis**: (If disease inquiry): State identified disease, scientific name, **Confidence: High/Medium/Low (<percentage>%)**, and **Severity: <Severity>**.
3. **Immediate Treatment**: Group into numbered/bulleted subheadings:
   - **Chemical Control**: Product name, dosage, instructions, and **Pre-Harvest Interval (PHI)** caution.
   - **Organic Treatment**: Botanical/organic formulation and method.
   - **Cultural Management**: Water/field management practices.
4. **Prevention**: Bulleted proactive cultural and seed prevention practices.
5. **Weather & Microclimate Advisory**: Current conditions, disease/pest risk warning, and spraying window guidance.
6. **Sources**: List cited Department of Agriculture/IRRI guide publications from the context.
7. **Disclaimer**: Exact text: "{ADVISORY_DISCLAIMER}"
8. **Follow-up & Helpline**: Short prompt inviting next question + "Helpline: {AGRICULTURE_HELPLINE}"

Ensure strict grounding in the provided context (BR-9)."""
        return user_prompt.strip()


